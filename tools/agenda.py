def plan(today=None):
    """오늘의 기사 계획. 주말이면 None — 발행하지 않는다.

    날짜만으로 결정된다. 같은 날 두 번 돌려도 결과가 같고, 지난 날짜로 돌리면
    그날 나왔어야 할 계획이 그대로 재현된다.

    주제는 날짜 일련번호를 주제 수로 나눈 나머지로 고른다. 주말이 이틀을 소비하므로
    매주 배치가 밀려, 같은 주제가 늘 같은 요일에 오지 않는다.
    """
    day = today or datetime.date.today()
    wd = day.weekday()

    if wd >= 5:                                   # 토·일은 쉰다
        return None
    if wd == WEEKLY_DAY:                          # 금요일: 한 주 정리
        kind, spec, theme = "weekly", WEEKLY_SET, "주간리뷰"
    else:
        kind = "daily"
        theme = WEEKDAY_THEMES[day.toordinal() % len(WEEKDAY_THEMES)]
        spec = THEMES[theme]

    return {
        "주제": theme,
        "형식": kind,
        "형식이름": FORMATS[kind]["이름"],
        "지시": FORMATS[kind]["지시"],
        "제목힌트": spec["제목"],
        "사진검색어": spec["사진"],
        "지표": spec["지표"],
        "날짜": day.isoformat(),
    }
